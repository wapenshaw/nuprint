r"""Generate SC03h parity fixtures for the Rust port from the Python reference.

Run from poc/python:  .\.venv\Scripts\python.exe tools\gen_fixtures.py
Writes ../../fixtures/sc03h/. Inputs are synthetic canonical bitmaps
(row-major, MSB-first, 1 = black); expected outputs are the exact bytes the
verified Python encoder produces for them.
"""

import hashlib
import json
from pathlib import Path
from PIL import Image
from nuprint.protocol import FrameDecoder, crc8, packet, print_job, WIDTH
from nuprint.render import test_image

OUT = Path(__file__).resolve().parents[3] / "fixtures" / "sc03h"


def canonical_rows(image: Image.Image) -> str:
    # Pillow mode 1 is MSB-first with 1 = white; canonical storage is 1 = black.
    return bytes(b ^ 0xFF for b in image.tobytes()).hex()


def pattern(name: str, height: int, black) -> Image.Image:
    image = Image.new("1", (WIDTH, height), 1)
    for y in range(height):
        for x in range(WIDTH):
            if black(x, y):
                image.putpixel((x, y), 0)
    return image


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    bitmaps = {
        "edges": pattern("edges", 2, lambda x, y: (x, y) in {(0, 0), (7, 1), (8, 1), (383, 1)}),
        "all-black": pattern("all-black", 1, lambda x, y: True),
        "checker": pattern("checker", 8, lambda x, y: (x // 8 + y) % 2 == 0),
        "asymmetric": pattern("asymmetric", 5, lambda x, y: x < 3 + y * 5 or x == 383 - y),
    }
    jobs = []
    for name, image in bitmaps.items():
        for darkness in ("light", "normal", "dark"):
            for feed in (0, 1, 3, 6, 7, 12):
                if darkness != "normal" and feed not in (0, 12):
                    continue
                data = print_job(image, darkness, feed_mm=feed)
                jobs.append({"bitmap": name, "darkness": darkness, "feed_mm": feed,
                             "job_hex": data.hex(), "job_sha256": hashlib.sha256(data).hexdigest()})
    strip = test_image()
    strip_path = OUT / "verified-strip.png"
    strip.save(strip_path, format="PNG")
    strip_job = print_job(strip, "normal", feed_mm=12)
    fixture = {
        "source": "Generated by poc/python/tools/gen_fixtures.py from the verified Python encoder",
        "bitmap_convention": "row-major, MSB-first, 1 = black, stride ceil(width/8)",
        "crc8_check": {"input_ascii": "123456789", "crc": crc8(b"123456789")},
        "commands": [
            {"opcode": op, "payload_hex": payload.hex(), "frame_hex": packet(op, payload).hex()}
            for op, payload in [(0xA3, b"\x00"), (0xA4, b"\x33"), (0xA1, b"\x30\x00"), (0xBE, b"\x01"),
                                (0xA8, b"\x00"), (0xAF, (5000).to_bytes(2, "little")), (0xBD, b"\x0a")]
        ],
        "responses": [
            {"name": "status-ready", "hex": "5178a301030000122788ff", "opcode": 0xA3, "payload_hex": "001227"},
            {"name": "device-info", "hex": "5178a8010a00810003332e302e34390015ff", "opcode": 0xA8,
             "payload_hex": "810003332e302e343900"},
            {"name": "flow-pause", "hex": packet(0xAE, b"\x10", flags=1).hex(), "opcode": 0xAE, "payload_hex": "10"},
            {"name": "flow-resume", "hex": packet(0xAE, b"\x00", flags=1).hex(), "opcode": 0xAE, "payload_hex": "00"},
        ],
        "bitmaps": {name: {"width": WIDTH, "height": image.height, "rows_hex": canonical_rows(image)}
                    for name, image in bitmaps.items()},
        "jobs": jobs,
        "verified_strip": {
            "png": "verified-strip.png", "width": strip.width, "height": strip.height,
            "rows_sha256": hashlib.sha256(bytes.fromhex(canonical_rows(strip))).hexdigest(),
            "job_normal_feed12_sha256": hashlib.sha256(strip_job).hexdigest(),
            "job_len": len(strip_job),
        },
    }
    for response in fixture["responses"]:  # Captured replies must decode with the reference decoder.
        frames = FrameDecoder().feed(bytes.fromhex(response["hex"]))
        assert len(frames) == 1 and frames[0].payload.hex() == response["payload_hex"], response["name"]
    (OUT / "vectors.json").write_text(json.dumps(fixture, indent=1) + "\n", encoding="utf-8")
    print(f"Wrote {OUT / 'vectors.json'} ({len(jobs)} jobs) and {strip_path}")


if __name__ == "__main__":
    main()
